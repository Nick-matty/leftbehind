// Multi-language support. English is the complete reference translation;
// every other language covers the full key set. Languages not listed here
// automatically fall back to English rather than showing broken text.
// RTL languages (Arabic, Urdu) are flagged via isRTL() below.

export type LanguageCode =
  | 'en' | 'es' | 'fr' | 'de' | 'pt' | 'it' | 'ru' | 'zh' | 'ja' | 'ko'
  | 'ar' | 'hi' | 'tr' | 'nl' | 'pl' | 'sw' | 'vi' | 'th' | 'id' | 'bn' | 'ur';

